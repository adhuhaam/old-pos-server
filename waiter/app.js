function bindPull() {
  let startY = 0;
  let tracking = false;
  app.addEventListener('touchstart', (event) => {
    tracking = app.scrollTop <= 0 && event.touches.length === 1;
    startY = tracking ? event.touches[0].clientY : 0;
  }, { passive: true });
  app.addEventListener('touchend', (event) => {
    if (!tracking) {
      return;
    }
    const pull = event.changedTouches[0].clientY - startY;
    tracking = false;
    if (pull > 72 && app.scrollTop <= 0) {
      pullReload();
    }
  }, { passive: true });
}

async function pullReload() {
  if (state.busy || state.pendingPay || app.classList.contains('refreshing')) {
    return;
  }
  if (state.screen === 'pin' || state.screen === 'account' || state.screen === 'spend' || state.screen === 'success') {
    return;
  }
  app.classList.add('refreshing');
  try {
    if (state.screen === 'customers') {
      const data = await api('/customers/book');
      if (state.screen !== 'customers') {
        return;
      }
      state.bookRows = data.customers || [];
      rememberPending(state.bookRows);
      state.canApprove = !!data.can_approve;
    } else {
      await refreshFloor();
    }
    if (!state.busy) {
      paintLive();
    }
  } catch (error) {
    if (!handleAuth(error)) {
      state.error = error.message;
      render();
    }
  } finally {
    app.classList.remove('refreshing');
  }
}

