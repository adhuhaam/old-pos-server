function bindProofPick() {
  const take = (input) => {
    const file = input.files && input.files[0];
    if (!file) return;
    keepSpendDraft();
    clearProof();
    state.proofFile = file;
    if (file.type.indexOf('image/') === 0) {
      state.proofPreview = URL.createObjectURL(file);
    }
    render();
  };
  [['proof-camera', 'proof-camera-file'], ['proof-gallery', 'proof-gallery-file'], ['proof-file', 'proof-doc-file']].forEach((pair) => {
    const button = document.getElementById(pair[0]);
    const input = document.getElementById(pair[1]);
    if (!button || !input) return;
    button.addEventListener('click', () => input.click());
    input.addEventListener('change', () => take(input));
  });
}

