function salesAtEnd() {
  const today = todayKey();
  const span = state.salesSpan || 'day';
  if (span === 'all') {
    return true;
  }
  if (span === 'year') {
    return Number(state.salesDate.slice(0, 4)) >= Number(today.slice(0, 4));
  }
  if (span === 'month') {
    return state.salesDate.slice(0, 7) >= today.slice(0, 7);
  }
  if (span === 'week') {
    return shiftDate(state.salesDate, 7) > today && state.salesDate >= shiftDate(today, -((new Date(today + 'T12:00:00').getDay() + 6) % 7));
  }
  return state.salesDate >= today;
}

function shiftSales(step) {
  const span = state.salesSpan || 'day';
  if (span === 'all') {
    return;
  }
  const today = todayKey();
  if (span === 'year') {
    const year = Number(state.salesDate.slice(0, 4)) + step;
    const thisYear = Number(today.slice(0, 4));
    if (year < 2020 || year > thisYear) {
      return;
    }
    state.salesDate = year === thisYear ? today : year + '-01-01';
  } else if (span === 'month') {
    const parts = state.salesDate.split('-');
    const date = new Date(Number(parts[0]), Number(parts[1]) - 1 + step, 1);
    let next = date.getFullYear() + '-' + String(date.getMonth() + 1).padStart(2, '0') + '-01';
    if (next.slice(0, 7) > today.slice(0, 7)) {
      return;
    }
    if (next.slice(0, 7) === today.slice(0, 7)) {
      next = today;
    }
    state.salesDate = next;
  } else {
    const next = shiftDate(state.salesDate, step * (span === 'week' ? 7 : 1));
    if (next > today) {
      return;
    }
    state.salesDate = next;
  }
  loadSales();
}

