function chartAxisLabel(cents) {
  const units = cents / 100;
  const abs = Math.abs(units);
  if (abs >= 1000000) {
    return String(Math.round(units / 100000) / 10).replace(/\.0$/, '') + 'm';
  }
  if (abs >= 1000) {
    return String(Math.round(units / 100) / 10).replace(/\.0$/, '') + 'k';
  }
  return String(Math.round(units));
}

function chartHtml(days) {
  const rows = days || [];
  if (!rows.length) {
    return '';
  }
  const sales = rows.map((day) => toCents(day.sales) + toCents(day.recorded || 0));
  let max = 1;
  sales.forEach((cents) => {
    max = Math.max(max, cents);
  });
  const plotTop = 4;
  const plotBottom = 44;
  const plotLeft = 2;
  const plotRight = 358;
  const yOf = (cents) => Math.round((plotBottom - (cents / max) * (plotBottom - plotTop)) * 10) / 10;
  const count = rows.length;
  const xOf = (index) => {
    if (count === 1) {
      return Math.round(((plotLeft + plotRight) / 2) * 10) / 10;
    }
    return Math.round((plotLeft + index * ((plotRight - plotLeft) / (count - 1))) * 10) / 10;
  };
  const path = sales.map((cents, index) => (index === 0 ? 'M' : 'L') + xOf(index) + ' ' + yOf(cents)).join(' ');
  const step = count > 20 ? 5 : (count > 10 ? 2 : 1);
  const chosen = rows.findIndex((day) => day.current);
  const onIndex = chosen >= 0 ? chosen : count - 1;
  const labels = rows.map((day, index) => {
    const show = index % step === 0 || index === count - 1;
    const axis = day.axis || String(Number(String(day.date).slice(8)) || '');
    return '<span' + (index === onIndex ? ' class="on"' : '') + '>' + (show ? esc(axis) : '') + '</span>';
  }).join('');
  return '<div class="line-chart" id="today-chart"><svg viewBox="0 0 360 48" role="img" aria-label="' + esc(t('sales')) + '"><path class="sale" d="' + path + '"/></svg><div class="line-cols">' + labels + '</div></div>';
}

