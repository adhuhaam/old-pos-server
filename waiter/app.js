async function refreshFloor() {
  if (document.hidden || state.busy || state.pendingPay || state.screen === 'pin' || state.screen === 'account' || state.screen === 'spend') {
    return;
  }
  const field = document.activeElement;
  if (field && (field.tagName === 'INPUT' || field.tagName === 'TEXTAREA' || field.tagName === 'SELECT')) {
    return;
  }
  const screen = state.screen;
  const live = screen === 'tables' || screen === 'bills' || screen === 'credits' || screen === 'menu' || screen === 'pay' || screen === 'sales' || screen === 'ticket';
  if (!live) {
    return;
  }
  const watchBill = screen === 'pay' && state.order && state.order.can_edit === false;
  try {
    const floor = await api('/tables');
    if (state.screen !== screen || document.hidden) {
      return;
    }
    const nextTables = tableStamp(floor.tables);
    const tablesChanged = nextTables !== state.tableStamp;
    state.tableStamp = nextTables;
    state.tables = floor.tables;
    const nextPending = Number(floor.pending_payments || 0);
    if (nextPending !== state.pendingPayments) {
      state.pendingPayments = nextPending;
      if (screen === 'tables' || screen === 'bills') {
        changed = true;
      }
    }
    state.currency = floor.currency_symbol;
    if (floor.cafe_name) {
      state.cafeName = floor.cafe_name;
    }
    let changed = tablesChanged && (screen === 'tables' || screen === 'bills');
    if (shiftKey(floor.shift) !== shiftKey(state.shift)) {
      state.shift = floor.shift || null;
      if (screen === 'tables') {
        changed = true;
      }
    }
    const nextMenu = floor.menu_stamp || '';
    if (nextMenu !== state.menuStamp) {
      state.menuStamp = nextMenu;
      if (screen === 'menu') {
        state.menu = await api('/menu');
        if (state.screen !== screen || document.hidden) {
          return;
        }
        state.menuLoadedStamp = state.menuStamp;
        changed = true;
      }
    }
    const nextCredit = floor.credit_stamp || '';
    if (nextCredit !== state.creditStamp) {
      state.creditStamp = nextCredit;
      const data = await api('/credit');
      if (state.screen !== screen || document.hidden) {
        return;
      }
      const nextList = creditListStamp(data.credits || []);
      if (nextList !== creditListStamp(state.credits)) {
        state.credits = data.credits || [];
        if (screen === 'credits' || screen === 'tables' || screen === 'bills' || screen === 'sales') {
          changed = true;
        }
      }
    }
    if (watchBill && state.order) {
      const fresh = await api('/orders/' + state.order.id);
      if (state.screen !== screen || document.hidden) {
        return;
      }
      const linesChanged = creditListStamp(fresh.lines) !== creditListStamp(state.order.lines);
      if (linesChanged || fresh.total !== state.order.total || fresh.status !== state.order.status) {
        state.order = fresh;
        changed = true;
      }
    }
    if (screen === 'sales' && (state.salesSpan || 'day') === 'day' && state.salesDate === todayKey()) {
      const report = await api('/sales', { query: 'date=' + encodeURIComponent(state.salesDate) });
      if (state.screen !== screen || document.hidden) {
        return;
      }
      const nextSales = salesStamp(report);
      if (nextSales !== state.salesStamp) {
        state.sales = report;
        state.salesStamp = nextSales;
        if (report.currency_symbol) {
          state.currency = report.currency_symbol;
        }
        changed = true;
      }
    }
    if (screen === 'sales' && state.salesDate && salesAtEnd()) {
      const overview = await api('/overview', { query: 'span=' + encodeURIComponent(state.salesSpan || 'day') + '&date=' + encodeURIComponent(state.salesDate) });
      if (state.screen !== screen || document.hidden) {
        return;
      }
      const nextOverview = overviewStamp(overview);
      if (nextOverview !== state.overviewStamp) {
        state.overview = overview;
        state.overviewStamp = nextOverview;
        changed = true;
      }
    }
    if (changed) {
      paintLive();
    } else {
      syncTabBadge('bills', openBillCount());
      syncTabBadge('credits', (state.credits || []).length);
    }
  } catch (error) {
    if (error.status === 401) {
      signOut();
    }
  }
}

