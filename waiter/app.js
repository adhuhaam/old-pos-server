async function settleCustomerCredits(method) {
  const saleIds = [];
  ((state.bookDetail && state.bookDetail.bills) || []).forEach((bill) => {
    if (bill.status === 'credit' && bill.pay_review !== 'pending' && state.creditSettleIds[bill.id] !== false) {
      saleIds.push(bill.id);
    }
  });
  if (!saleIds.length) {
    state.error = 'Choose at least one bill.';
    render();
    return;
  }
  state.busy = true;
  state.error = '';
  render();
  try {
    state.receipt = await api('/settlements', {
      method: 'POST',
      body: {
        payment_method: method,
        customer_id: state.bookId,
        sale_ids: saleIds,
      },
    });
    state.creditSettle = false;
    state.creditSettleIds = {};
    state.billFrom = 'customer';
    state.screen = 'success';
  } catch (error) {
    if (!handleAuth(error)) {
      state.error = error.message;
      state.screen = 'customer';
    }
  } finally {
    state.busy = false;
    render();
  }
}

