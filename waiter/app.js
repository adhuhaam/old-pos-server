function settleTotals() {
  let current = 0;
  let credit = 0;
  let tables = 0;
  let count = 0;
  if (state.settleInclude && state.order) {
    current = toCents(state.order.total);
    count += 1;
  }
  (state.settleCredits || []).forEach((bill) => {
    if (bill.id !== (state.order && state.order.id) && state.settleIds[bill.id]) {
      credit += toCents(bill.total);
      count += 1;
    }
  });
  runningTableBills().forEach((table) => {
    if (state.settleIds[table.order_id]) {
      tables += toCents(table.total);
      count += 1;
    }
  });
  return { current: current, credit: credit, tables: tables, count: count, total: current + credit + tables };
}

