const itemPhotoBlobs = {};

function itemPhotoUrl(item) {
  if (!item || !item.photo) {
    return '';
  }
  return apiUrl('/items/' + item.id + '/photo') + '&v=' + encodeURIComponent(item.photo);
}

function itemPhotoSlot(item) {
  const key = item.id + ':' + item.photo;
  const known = itemPhotoBlobs[key] || '';
  return '<img class="item-photo" alt="" data-photo="' + item.id + '" data-photo-key="' + esc(key) + '"' + (known ? ' src="' + known + '"' : '') + '>';
}

async function loadItemPhotos() {
  const images = [...app.querySelectorAll('img[data-photo]')];
  await Promise.all(images.map(async (img) => {
    const key = img.getAttribute('data-photo-key') || '';
    if (itemPhotoBlobs[key]) {
      img.src = itemPhotoBlobs[key];
      return;
    }
    const id = img.getAttribute('data-photo');
    const token = key.slice(String(id).length + 1);
    try {
      const headers = {};
      const auth = localStorage.getItem('cafe_pos_token');
      if (auth) {
        headers.Authorization = 'Bearer ' + auth;
        headers['X-Auth-Token'] = auth;
      }
      const response = await fetch(itemPhotoUrl({ id: id, photo: token }), { headers });
      if (!response.ok) {
        return;
      }
      const url = URL.createObjectURL(await response.blob());
      itemPhotoBlobs[key] = url;
      const current = [...app.querySelectorAll('img[data-photo]')].find((node) => node.getAttribute('data-photo-key') === key);
      if (current) {
        current.src = url;
      }
    } catch (error) {}
  }));
}

