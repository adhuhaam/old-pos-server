function customerCardsHtml() {
  const rows = customerMatches().slice().sort((a, b) => {
    const due = toCents(b.open_total) - toCents(a.open_total);
    if (due !== 0) {
      return due;
    }
    return String(a.name || '').localeCompare(String(b.name || ''));
  });
  if (!rows.length) {
    return '<p class="muted">' + esc(state.bookRows.length ? t('noCreditMatch') : t('noCustomers')) + '</p>';
  }
  return rows.map((row) => {
    const due = toCents(row.open_total) > 0;
    const old = customerPastMonth(row);
    const bills = Number(row.open_bills) || 0;
    return '<button class="person-row" type="button" data-customer="' + row.id + '">' +
      personMark() +
      '<span class="person-id"><strong' + (old ? ' class="old"' : '') + '>' + esc(row.name) + '</strong><span>' + esc(row.phone) + '</span>' +
      (Number(row.pending_bills) > 0 ? '<em>' + esc(t('waitingPay')) + '</em>' : '') +
      '</span>' +
      '<span class="person-hold' + (due ? ' due' : '') + '"><small>' + bills + ' ' + esc(t('tickets')) + '</small><strong>' + esc(money(row.open_total)) + '</strong></span>' +
      '</button>';
  }).join('');
}

