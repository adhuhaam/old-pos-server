function fitCanvasText(ctx, text, maxWidth) {
  let value = String(text);
  if (ctx.measureText(value).width <= maxWidth) {
    return value;
  }
  while (value.length > 1 && ctx.measureText(value + '…').width > maxWidth) {
    value = value.slice(0, -1);
  }
  return value + '…';
}

