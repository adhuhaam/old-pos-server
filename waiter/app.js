async function saveAccount() {
  if (state.busy) {
    return;
  }
  const name = document.getElementById('account-name').value;
  const currentPassword = document.getElementById('account-current').value;
  const newPassword = document.getElementById('account-new').value;
  if (!state.profile) {
    state.profile = { name: name, username: '' };
  } else {
    state.profile.name = name;
  }
  state.busy = true;
  state.error = '';
  state.accountSaved = '';
  render();
  try {
    state.profile = await api('/me', {
      method: 'POST',
      body: { name: name, current_password: currentPassword, new_password: newPassword },
    });
    state.accountSaved = t('saved');
  } catch (error) {
    if (!handleAuth(error)) {
      state.error = error.message;
    }
    if (!state.profile) {
      state.profile = { name: name, username: '' };
    } else {
      state.profile.name = name;
    }
  } finally {
    state.busy = false;
    if (state.screen === 'account') {
      render();
    }
  }
}

