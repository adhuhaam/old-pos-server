function receiptGroups(lines) {
  const groups = [];
  (lines || []).forEach((line) => {
    const day = line.added_at ? String(line.added_at).slice(0, 10) : '';
    const last = groups[groups.length - 1];
    if (!last || last.day !== day) {
      groups.push({ day: day, lines: [line] });
    } else {
      last.lines.push(line);
    }
  });
  return groups;
}

function billSerial(id) {
  const number = Number(id || 0);
  return number > 0 ? String(number).padStart(4, '0') : '';
}

