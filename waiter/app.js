function creditMatches() {
  const query = state.creditQuery.trim().toLowerCase();
  const digits = query.replace(/\D+/g, '');
  return (state.credits || []).filter((credit) => {
    if (query === '') {
      return true;
    }
    const name = String(credit.customer_name || '').toLowerCase();
    const phone = String(credit.customer_phone || '');
    const table = String(credit.table_name || '').toLowerCase();
    return name.indexOf(query) !== -1
      || table.indexOf(query) !== -1
      || phone.toLowerCase().indexOf(query) !== -1
      || (digits !== '' && phone.indexOf(digits) !== -1);
  });
}

