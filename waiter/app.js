function toCents(price) {
  const clean = String(price).replace(/,/g, '').trim();
  const negative = clean.charAt(0) === '-';
  const parts = (negative ? clean.slice(1) : clean).split('.');
  const whole = parseInt(parts[0], 10) || 0;
  const fraction = (parts[1] || '0').padEnd(2, '0').slice(0, 2);
  const cents = whole * 100 + (parseInt(fraction, 10) || 0);
  return negative ? -cents : cents;
}

function fromCents(cents) {
  const negative = cents < 0;
  const abs = Math.abs(cents);
  return (negative ? '-' : '') + Math.floor(abs / 100) + '.' + String(abs % 100).padStart(2, '0');
}

function formatAmount(cents) {
  const negative = cents < 0;
  const abs = Math.abs(cents);
  const whole = String(Math.floor(abs / 100)).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
  return (negative ? '-' : '') + whole + '.' + String(abs % 100).padStart(2, '0');
}

function money(amount) {
  const symbol = (state.currency || 'MVR').trim();
  const gap = /[A-Za-z]$/.test(symbol) ? ' ' : '';
  return symbol + gap + formatAmount(toCents(amount));
}

function formatElapsed(iso) {
  const start = Date.parse(iso);
  if (Number.isNaN(start)) {
    return '';
  }
  let seconds = Math.floor((Date.now() - start) / 1000);
  if (seconds < 0) {
    seconds = 0;
  }
  const hours = Math.floor(seconds / 3600);
  const minutes = Math.floor((seconds % 3600) / 60);
  const secs = seconds % 60;
  const clock = minutes + ':' + String(secs).padStart(2, '0');
  return hours > 0 ? hours + ':' + String(minutes).padStart(2, '0') + ':' + String(secs).padStart(2, '0') : clock;
}

