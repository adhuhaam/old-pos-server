function proofHint(categoryId) {
  const cat = (state.expenseCategories || []).find((row) => String(row.id) === String(categoryId));
  const name = cat ? String(cat.name).toLowerCase() : '';
  if (name.indexOf('rent') !== -1 || name.indexOf('suppl') !== -1 || name.indexOf('util') !== -1) {
    return t('proofBill');
  }
  return t('proofOptional');
}

function supplyWeekHtml() {
  const week = state.supplyWeek;
  if (!week) {
    return '';
  }
  const lines = week.lines || [];
  if (!lines.length) {
    return '<section class="account"><h2>' + esc(t('weekSupply')) + '</h2><p class="muted">' + esc(t('supplyEmpty')) + '</p></section>';
  }
  const status = String(week.status || '');
  const locked = status === 'quoted' || status === 'accepted';
  const note = status === 'accepted' ? t('supplyAccepted') : (status === 'quoted' ? t('supplyQuoted') : (status === 'requested' ? t('supplyWaiting') : ''));
  const fields = lines.map((line) => {
    const qty = status === '' ? (line.prefill_qty || '') : (line.requested_qty && Number(line.requested_qty) > 0 ? line.requested_qty : '');
    const unit = line.unit ? ' <span class="muted">' + esc(line.unit) + '</span>' : '';
    if (locked) {
      if (!(Number(line.requested_qty) > 0)) {
        return '';
      }
      const priced = line.quote_price ? ' · ' + esc(money(line.quote_price)) : '';
      return '<p><strong>' + esc(line.name) + '</strong>' + unit + ' · ' + esc(line.requested_qty) + priced + '</p>';
    }
    return '<label>' + esc(line.name) + unit +
      '<input data-supply-item="' + esc(line.item_id) + '" inputmode="decimal" value="' + esc(qty || '') + '"></label>';
  }).join('');
  const button = locked ? '' : '<button class="primary" type="submit"' + (state.busy ? ' disabled' : '') + '>' + esc(status === 'requested' ? t('supplyUpdate') : t('supplyRequest')) + '</button>';
  const total = week.total ? '<p class="bill-total"><span>' + esc(t('supplies')) + '</span><strong>' + esc(money(week.total)) + '</strong></p>' : '';
  return '<form class="account" id="supply-form"><h2>' + esc(t('weekSupply')) + ' · ' + esc(week.week_label || '') + '</h2>' +
    (note ? '<p class="hint">' + esc(note) + '</p>' : '') +
    fields + total + button + '</form>';
}

