async function leaveTable(destination) {
  state.busy = true;
  state.error = '';
  state.pendingPay = null;
  clearSlip();
  state.ticket = null;
  const order = state.order;
  const backToCustomer = destination !== 'tables' && state.billFrom === 'customer';
  const backToSales = !backToCustomer && destination !== 'tables' && state.billFrom === 'sales';
  const backToCredits = !backToCustomer && !backToSales && destination !== 'tables' && (state.billFrom === 'credits' || (order && order.status === 'credit' && state.billFrom !== 'tables'));
  state.order = null;
  state.tableId = null;
  state.tableName = '';
  if (backToCustomer) {
    state.screen = 'customer';
  } else if (backToSales) {
    state.screen = 'sales';
  } else if (backToCredits) {
    state.billFrom = 'credits';
    state.screen = 'customers';
  }
  try {
    if (!backToCustomer && !backToCredits && !backToSales && order && order.status !== 'credit' && order.can_edit !== false && order.lines && order.lines.length === 0) {
      await api('/orders/' + order.id + '/cancel', { method: 'POST', body: {} });
    }
    if (backToCustomer) {
      await openCustomer(state.bookId);
    } else if (backToSales) {
      await loadCredits();
      await loadSales();
    } else if (backToCredits) {
      const data = await api('/credit');
      state.credits = data.credits || [];
      await openCustomers();
    } else {
      await loadFloor();
    }
  } catch (error) {
    if (!handleAuth(error)) {
      state.error = error.message;
      state.screen = backToSales ? 'sales' : (backToCustomer ? 'customer' : (backToCredits ? 'customers' : 'tables'));
    }
  } finally {
    state.busy = false;
    render();
  }
}

