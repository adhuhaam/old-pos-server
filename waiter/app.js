function customerMatches() {
  const query = state.bookQuery.trim().toLowerCase();
  const digits = query.replace(/\D+/g, '');
  return (state.bookRows || []).filter((row) => {
    if (!query) {
      return true;
    }
    const name = String(row.name || '').toLowerCase();
    const phone = String(row.phone || '');
    return name.indexOf(query) !== -1
      || phone.toLowerCase().indexOf(query) !== -1
      || (digits !== '' && phone.indexOf(digits) !== -1);
  });
}

function customerCreditCents(rows) {
  return (rows || []).reduce((sum, row) => sum + toCents(row.open_total), 0);
}

function customerPastMonth(row) {
  const raw = String((row && row.created_at) || '').trim().replace(' ', 'T');
  const added = new Date(raw);
  if (!raw || Number.isNaN(added.getTime())) {
    return false;
  }
  const monthAgo = new Date();
  monthAgo.setMonth(monthAgo.getMonth() - 1);
  return added < monthAgo;
}

