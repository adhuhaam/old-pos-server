function todayKey() {
  const now = new Date();
  return now.getFullYear() + '-' + String(now.getMonth() + 1).padStart(2, '0') + '-' + String(now.getDate()).padStart(2, '0');
}

function shiftDate(date, days) {
  const parsed = new Date(date + 'T12:00:00');
  parsed.setDate(parsed.getDate() + days);
  return parsed.getFullYear() + '-' + String(parsed.getMonth() + 1).padStart(2, '0') + '-' + String(parsed.getDate()).padStart(2, '0');
}

const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

function dayLabel(date) {
  const parts = String(date).split('-');
  const month = MONTHS[Number(parts[1]) - 1];
  if (parts.length !== 3 || !month) {
    return String(date);
  }
  return String(parts[2]).padStart(2, '0') + ' ' + month + ' ' + parts[0];
}

function salesDayLabel(date) {
  return dayLabel(String(date).slice(0, 10));
}

function dateLabel(value) {
  const text = String(value);
  const day = text.slice(0, 10);
  if (/^\d{4}-\d{2}-\d{2}/.test(day)) {
    return dayLabel(day);
  }
  const parsed = new Date(text.replace(' ', 'T'));
  if (Number.isNaN(parsed.getTime())) {
    return '';
  }
  const month = MONTHS[parsed.getMonth()] || '';
  return String(parsed.getDate()).padStart(2, '0') + ' ' + month + ' ' + parsed.getFullYear();
}

function clockLabel(value) {
  const parsed = new Date(String(value).replace(' ', 'T'));
  if (Number.isNaN(parsed.getTime())) {
    return '';
  }
  let hours = parsed.getHours();
  const mins = String(parsed.getMinutes()).padStart(2, '0');
  const suffix = hours >= 12 ? 'PM' : 'AM';
  hours = hours % 12 || 12;
  return hours + ':' + mins + ' ' + suffix;
}

