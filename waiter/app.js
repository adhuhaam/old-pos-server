function salesStamp(report) {
  if (!report || !report.summary) {
    return '';
  }
  const summary = report.summary;
  const sales = (report.sales || []).map((row) => [row.id, row.total, row.payment_method, row.customer_name || '', row.customer_phone || ''].join(':')).join(',');
  const credits = (report.credits || []).map((row) => [row.id, row.total, row.customer_name || ''].join(':')).join(',');
  const open = (report.open || []).map((row) => [row.id, row.total].join(':')).join(',');
  return [summary.count, summary.total, summary.cash_total, summary.online_total, summary.credit_open, sales, credits, open].join('|');
}

function syncTabBadge(tab, count) {
  const button = document.querySelector('.tabs [data-tab="' + tab + '"] .tab-ico');
  if (!button) {
    return;
  }
  let badge = button.querySelector('.tab-count');
  if (!count) {
    if (badge) {
      badge.remove();
    }
    return;
  }
  if (!badge) {
    badge = document.createElement('span');
    badge.className = 'tab-count';
    button.appendChild(badge);
  }
  badge.textContent = String(count);
}

