function spendMonthTitle(month) {
  const parts = String(month || '').split('-');
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  const name = months[Number(parts[1]) - 1];
  return name ? name + ' ' + parts[0] : month;
}

function shiftMonth(month, delta) {
  const parts = String(month || todayKey().slice(0, 7)).split('-');
  const date = new Date(Number(parts[0]), Number(parts[1]) - 1 + delta, 1);
  return date.getFullYear() + '-' + String(date.getMonth() + 1).padStart(2, '0');
}

