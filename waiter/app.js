async function loadCustomers(query) {
  const request = ++customerRequest;
  try {
    const data = await api('/customers', { query: 'q=' + encodeURIComponent(query) });
    if (request !== customerRequest || (state.creditChoice !== 'existing' && state.pendingPay !== 'settle')) {
      return;
    }
    state.customerHits = data.customers || [];
    const list = document.getElementById('customer-list');
    if (!list) {
      render();
      return;
    }
    list.innerHTML = customerHitsHtml();
    bindCustomerPicks(list);
  } catch (error) {
    if (request !== customerRequest) {
      return;
    }
    if (!handleAuth(error)) {
      state.error = error.message;
      render();
    }
  }
}

async function loadBankPhoto() {
  const img = document.getElementById('bank-photo');
  if (!img) {
    return;
  }
  try {
    const headers = {};
    const token = localStorage.getItem('cafe_pos_token');
    if (token) {
      headers.Authorization = 'Bearer ' + token;
      headers['X-Auth-Token'] = token;
    }
    const response = await fetch(apiUrl('/bank-image'), { headers, cache: 'no-store' });
    if (!response.ok || !document.getElementById('bank-photo')) {
      img.hidden = true;
      const missing = document.getElementById('bank-missing');
      if (missing) {
        missing.hidden = false;
      }
      return;
    }
    const blob = await response.blob();
    const url = URL.createObjectURL(blob);
    const current = document.getElementById('bank-photo');
    if (!current) {
      URL.revokeObjectURL(url);
      return;
    }
    current.src = url;
  } catch (error) {
    img.hidden = true;
    const missing = document.getElementById('bank-missing');
    if (missing) {
      missing.hidden = false;
    }
  }
}

function menuItemArticle(item, categoryName) {
  const lines = state.order ? state.order.lines : [];
  const adding = canChangeBill();
  const onBill = adding ? lines.find((line) => line.item_id === item.id) : null;
  const label = itemLabel(item.name);
  const minus = onBill
    ? '<button class="step minus" type="button" data-dec="' + onBill.id + '" aria-label="' + esc(t('delete')) + '">−</button>'
    : '';
  const badge = onBill ? '<span class="qty-badge">' + onBill.qty + '</span>' : '';
  const main = adding
    ? '<button class="item-main" type="button" data-add="' + item.id + '">'
    : '<div class="item-main">';
  const end = adding ? '</button>' : '</div>';
  const photo = item.photo ? itemPhotoSlot(item) : '<span class="item-photo empty" aria-hidden="true"></span>';
  const sub = label.sub || categoryName || '';
  return '<article class="item">' + minus + photo + main +
      '<strong>' + esc(label.main) + '</strong>' +
      (sub ? '<span class="sub">' + esc(sub) + '</span>' : '') +
      '<span class="price">' + esc(money(item.price)) + '</span>' +
    end + badge + '</article>';
}

function menuItemsHtml() {
  const categories = state.menu ? state.menu.categories : [];
  const query = (state.menuQuery || '').trim().toLowerCase();
  if (query) {
    const hits = [];
    categories.forEach((category) => {
      (category.items || []).forEach((item) => {
        const label = itemLabel(item.name);
        const hay = (label.main + ' ' + (label.sub || '') + ' ' + item.name + ' ' + category.name).toLowerCase();
        if (hay.indexOf(query) !== -1) {
          hits.push(menuItemArticle(item, categoryLabel(category.name).main));
        }
      });
    });
    return hits.join('') || '<p class="muted">' + esc(t('noItems')) + '</p>';
  }
  const current = categories.find((category) => category.id === state.categoryId) || categories[0];
  if (!current || !current.items.length) {
    return '<p class="muted">' + esc(t('noItems')) + '</p>';
  }
  return current.items.map((item) => menuItemArticle(item)).join('');
}

